"""Build the A vs B vs C comparison from the newest run of each approach on a split.

    python -m eval.summarize --split dev

Writes eval/reports/comparison.md and eval/reports/summary.json (served by GET /metrics
and embedded in the README between the RESULTS markers).
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any

from eval.report import pct

REPORTS = Path(__file__).parent / "reports"
README = Path(__file__).parents[1] / "README.md"
NAMES = {"A": "A · OCR + regex", "B": "B · OCR + LLM", "C": "C · Vision LLM"}


def latest_runs(split: str) -> dict[str, dict[str, Any]]:
    runs: dict[str, dict[str, Any]] = {}
    for mpath in REPORTS.glob("*/metrics.json"):
        m = json.loads(mpath.read_text())
        run = m["run"]
        if run["split"] != split or run.get("overrides") or run.get("oracle_type") or run["run_id"].startswith("ci_"):
            continue  # only default-config runs enter the headline table
        prev = runs.get(run["approach"])
        if prev is None or (run["n_docs"], run["created"]) > (prev["run"]["n_docs"], prev["run"]["created"]):
            m["_dir"] = mpath.parent.name
            runs[run["approach"]] = m
    return dict(sorted(runs.items()))


def table(runs: dict[str, dict[str, Any]], split: str, link_base: str = "") -> str:
    # dev: the threshold recommended from this split's curve; test: the threshold fixed beforehand on dev
    thr_label = "rec. threshold (dev curve)" if split != "test" else "threshold (fixed on dev)"
    head = (f"| approach | n | field acc | doc acc (critical) | items F1 | hallucination | straight-through | "
            f"auto-approve error | {thr_label} | cost / 1k docs | latency p50 / p95 |\n"
            "|---|---|---|---|---|---|---|---|---|---|---|")
    rows = [head]
    for a, m in runs.items():
        o, rec = m["overall"], m["recommended_threshold"]
        if split == "test":
            stp, err, thr = pct(o["straight_through_rate"]), pct(o["auto_error_rate"]), m["run"]["threshold"]
        elif rec.get("threshold") is not None:
            stp, err, thr = pct(rec["stp_rate"]), pct(rec["auto_error_rate"]), rec["threshold"]
        else:
            stp, err, thr = "0% (none safe)", "–", None
        rows.append(f"| [{NAMES[a]}]({link_base}{m['_dir']}/report.md) | {o['n']} | {pct(o['field_accuracy'])} | "
                    f"{pct(o['doc_accuracy_critical'])} | {o['line_items']['f1']:.3f} | {pct(o['hallucination_rate'])} | "
                    f"{stp} | {err} | {thr} | ${o['cost_usd_per_1000']:.2f} "
                    f"(Rp{o['cost_idr_per_1000']:,.0f}) | {o['latency_p50_ms'] / 1000:.1f}s / "
                    f"{o['latency_p95_ms'] / 1000:.1f}s |")
    return "\n".join(rows)


def by_dirt(runs: dict[str, dict[str, Any]]) -> str:
    levels = ["clean", "light", "medium", "heavy"]
    rows = ["| approach | " + " | ".join(levels) + " |", "|---" * (len(levels) + 1) + "|"]
    for a, m in runs.items():
        cells = [pct(m["by_dirt"][lv]["doc_accuracy_critical"]) if lv in m["by_dirt"] else "–" for lv in levels]
        rows.append(f"| {NAMES[a]} | " + " | ".join(cells) + " |")
    return "\n".join(rows)


def by_type(runs: dict[str, dict[str, Any]]) -> str:
    types = ["faktur_pajak", "invoice", "receipt"]
    rows = ["| approach | " + " | ".join(types) + " |", "|---" * (len(types) + 1) + "|"]
    for a, m in runs.items():
        cells = [f"{pct(m['by_doc_type'][t]['field_accuracy'])} / {pct(m['by_doc_type'][t]['doc_accuracy_critical'])}"
                 if t in m["by_doc_type"] else "–" for t in types]
        rows.append(f"| {NAMES[a]} | " + " | ".join(cells) + " |")
    return "\n".join(rows)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", default="dev")
    ap.add_argument("--readme", action="store_true", help="also update the README results block")
    args = ap.parse_args()
    runs = latest_runs(args.split)
    if not runs:
        raise SystemExit(f"no runs for split {args.split}")

    def body_for(link_base: str) -> str:
        return "\n\n".join([
            f"Split `{args.split}` · dataset `{next(iter(runs.values()))['run']['dataset_version']}` · "
            "generated by `python -m eval.summarize` from `eval/reports/*/metrics.json`",
            table(runs, args.split, link_base),
            "**Document accuracy (all critical fields correct) by image quality**", by_dirt(runs),
            "**Field accuracy / document accuracy by document type**", by_type(runs),
        ])

    body = body_for("")
    (REPORTS / f"comparison_{args.split}.md").write_text(f"# Approach comparison\n\n{body}\n")
    summary = {"split": args.split, "approaches": [
        {"approach": NAMES[a], "n": m["overall"]["n"], "field_accuracy": round(m["overall"]["field_accuracy"], 4),
         "doc_accuracy": round(m["overall"]["doc_accuracy_critical"], 4),
         "items_f1": round(m["overall"]["line_items"]["f1"], 4),
         "recommended_threshold": m["recommended_threshold"].get("threshold"),
         "stp_at_threshold": m["recommended_threshold"].get("stp_rate"),
         "cost_usd_per_1000": round(m["overall"]["cost_usd_per_1000"], 3),
         "latency_p50_s": round(m["overall"]["latency_p50_ms"] / 1000, 2)} for a, m in runs.items()]}
    if args.split == "dev":
        (REPORTS / "summary.json").write_text(json.dumps(summary, indent=1))
    if args.readme and README.exists():
        text = README.read_text()
        start, end = f"<!-- RESULTS:{args.split}:START -->", f"<!-- RESULTS:{args.split}:END -->"
        block = f"{start}\n{body_for('eval/reports/')}\n{end}"
        text = re.sub(re.escape(start) + ".*" + re.escape(end), lambda _: block, text, flags=re.S)
        README.write_text(text)
    print(body)


if __name__ == "__main__":
    main()
