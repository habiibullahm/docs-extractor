START = date(2023, 1, 1)
END = date(2026, 9, 30)


@dataclass
class SynthDoc:
    doc_id: str
    doc_type: str
    gt: dict[str, Any]
    render: dict[str, Any] = field(default_factory=dict)  # extra display-only data


def _digits(rng: random.Random, n: int, first_nonzero: bool = True) -> str:
    s = "".join(str(rng.randint(0, 9)) for _ in range(n))
    if first_nonzero and s[0] == "0":
        s = str(rng.randint(1, 9)) + s[1:]
    return s


def gen_npwp(rng: random.Random, on: date) -> str:
    """15-digit legacy NPWP before 2024, mostly 16-digit afterwards."""
    if on.year >= 2024 and rng.random() < 0.7:
        return "0" + _digits(rng, 15)
    return _digits(rng, 15)


def gen_nik(rng: random.Random) -> str:
    # synthetic: province/city/district code + DDMMYY + 4-digit sequence
    prov = rng.choice(["31", "32", "33", "34", "35", "36", "51", "61", "73"])
    dd = rng.randint(1, 28) + (40 if rng.random() < 0.5 else 0)
    return f"{prov}{rng.randint(1, 79):02d}{rng.randint(1, 40):02d}{dd:02d}{rng.randint(1, 12):02d}{rng.randint(60, 99):02d}{rng.randint(1, 9999):04d}"


def _rand_date(rng: random.Random) -> date:
    return START + timedelta(days=rng.randint(0, (END - START).days))


def _round_price(x: float, step: int = 500) -> float:
    return float(int(round(x / step)) * step)


def _company(fake: Faker) -> str:
    return fake.company()


def _items(rng: random.Random, catalogue, n: int, allow_discount: bool) -> list[dict[str, Any]]:
    items = []
    for name, lo, hi in rng.sample(catalogue, n):
        qty = float(rng.choice([1, 1, 1, 2, 2, 3, 4, 5, 10, 12, 20]) if hi < 1_000_000 else rng.choice([1, 1, 2, 3]))
        price = _round_price(rng.uniform(lo, hi), 100 if hi < 100_000 else 1000)
        disc = 0.0
        if allow_discount and rng.random() < 0.2:
            disc = _round_price(qty * price * rng.choice([0.05, 0.1, 0.15]), 100)
        items.append({
            "description": name, "quantity": qty, "unit_price": price,
            "discount": disc if disc else None, "total": qty * price - disc, "is_adjustment": False,
        })
    return items


def _party(fake: Faker, rng: random.Random, on: date, company: bool = True, with_nik: bool = False) -> dict[str, Any]:
    return {
        "name": _company(fake) if company else fake.name(),
        "npwp": gen_npwp(rng, on),
        "nik": gen_nik(rng) if with_nik else None,
        "address": fake.address().replace("\n", ", "),
    }


def ppn_scheme_for(on: date, rng: random.Random) -> tuple[str, dict[str, Any]]:
    schemes = tax_rules()["ppn"]["schemes"]
    if on < date(2025, 1, 1):
        name = "ppn_11"
    else:
        name = "ppn_12_luxury" if rng.random() < 0.15 else "ppn_12_dpp_nilai_lain"
    return name, schemes[name]


def faktur_serial(rng: random.Random, on: date) -> tuple[str, str]:
    """Return (printed, digits)."""
    if on.year >= 2025:
        digits = f"0{rng.choice([1, 2, 4, 7])}0{on.year % 100:02d}" + _digits(rng, 12, first_nonzero=False)
        digits = digits[:17]
        return digits, digits
    kode = rng.choice(["010", "020", "030", "040", "070", "080"])
    printed = f"{kode}.{rng.choice(['000', '001'])}-{on.year % 100:02d}.{_digits(rng, 8)}"
    return printed, "".join(ch for ch in printed if ch.isdigit())


def gen_faktur(doc_id: str, rng: random.Random, fake: Faker, inconsistent: bool = False) -> SynthDoc:
    on = _rand_date(rng)
    scheme_name, scheme = ppn_scheme_for(on, rng)
    items = _items(rng, GOODS, rng.randint(1, 7), allow_discount=True)
    total = sum(i["total"] for i in items)
    discount = _round_price(total * rng.choice([0.0, 0.0, 0.0, 0.02, 0.05]), 100)
    dpp = round((total - discount) * scheme["dpp_factor"])
    ppn = round(dpp * scheme["rate"])
    ppnbm = round(dpp * 0.1) if scheme_name == "ppn_12_luxury" and rng.random() < 0.5 else 0
    if inconsistent:
        ppn = ppn + rng.choice([1000, 5000, -2500, 10000])
    printed_serial, serial = faktur_serial(rng, on)
    buyer_individual = rng.random() < 0.25
    seller = _party(fake, rng, on)
    seller["nik"] = None
    buyer = _party(fake, rng, on, company=not buyer_individual, with_nik=buyer_individual)
    if buyer_individual and on.year >= 2024:
        buyer["npwp"] = buyer["nik"]
    gt = {
        "doc_type": "faktur_pajak",
        "tax_invoice_number": serial,
        "date": on.isoformat(),
        "seller": seller,
        "buyer": buyer,
        "line_items": items,
        "total": float(total),
        "discount": float(discount) if discount else 0.0,
        "dpp": float(dpp),
        "ppn": float(ppn),
        "ppnbm": float(ppnbm),
        "document_inconsistent": inconsistent,
    }
    return SynthDoc(doc_id, "faktur_pajak", gt, {
        "printed_serial": printed_serial, "ppn_scheme": scheme_name,
        "city": fake.city(), "signer": fake.name(),
    })


def gen_invoice(doc_id: str, rng: random.Random, fake: Faker, inconsistent: bool = False) -> SynthDoc:
    on = _rand_date(rng)
    due = on + timedelta(days=rng.choice([7, 14, 14, 30, 30, 45, 60]))
    currency = "USD" if rng.random() < 0.1 else "IDR"
    items = _items(rng, GOODS, rng.randint(1, 8), allow_discount=False)
    if currency == "USD":
        for it in items:
            it["unit_price"] = round(it["unit_price"] / 16_000, 2)
            it["total"] = round(it["quantity"] * it["unit_price"], 2)
    subtotal = round(sum(i["total"] for i in items), 2)
    discount = round(subtotal * rng.choice([0, 0, 0, 0.05, 0.1]), 2 if currency == "USD" else 0)
    rate = rng.choice([0.11, 0.12, 0.11, 0.0]) if currency == "IDR" else 0.0
    tax = round((subtotal - discount) * rate, 2 if currency == "USD" else 0)
    total = round(subtotal - discount + tax, 2)
    if inconsistent:
        total = total + (rng.choice([1000, 10000, -5000]) if currency == "IDR" else 5.0)
    vendor = _party(fake, rng, on)
    vendor["nik"] = None
    if rng.random() < 0.4:
        vendor["npwp"] = None
    customer = {"name": _company(fake), "npwp": None, "nik": None, "address": fake.address().replace("\n", ", ")}
    bank = None
    if rng.random() < 0.7:
        bank = {"bank_name": rng.choice(BANKS), "account_number": _digits(rng, rng.choice([10, 13])), "account_name": vendor["name"]}
    prefix = rng.choice(["INV", "INV/", "SI-", "INV-"])
    number = f"{prefix}{on.year}{on.month:02d}{rng.randint(1, 9999):04d}" if not prefix.endswith("/") else f"INV/{on.year}/{rng.choice(['I','II','III','IV','V','VI','VII','VIII','IX','X','XI','XII'])}/{rng.randint(1, 999):03d}"
    gt = {
        "doc_type": "invoice",
        "invoice_number": number,
        "date": on.isoformat(),
        "due_date": due.isoformat(),
        "vendor": vendor,
        "customer": customer,
        "line_items": items,
        "subtotal": float(subtotal),
        "discount": float(discount),
        "tax": float(tax),
        "total": float(total),
        "currency": currency,
        "bank_account": bank or {"bank_name": None, "account_number": None, "account_name": None},
        "document_inconsistent": inconsistent,
    }
    return SynthDoc(doc_id, "invoice", gt, {"tax_rate": rate, "notes": fake.sentence(nb_words=8)})


def gen_receipt(doc_id: str, rng: random.Random, fake: Faker, inconsistent: bool = False) -> SynthDoc:
    on = _rand_date(rng)
    hh, mm = rng.randint(7, 22), rng.randint(0, 59)
    items = _items(rng, MENU, rng.randint(1, 9), allow_discount=False)
    for it in items:
        it["discount"] = None
    if rng.random() < 0.12:
        amount = -_round_price(sum(i["total"] for i in items) * 0.1, 100)
        items.append({"description": "DISKON MEMBER", "quantity": None, "unit_price": None,
                      "discount": None, "total": amount, "is_adjustment": True})
    subtotal = sum(i["total"] for i in items)
    service = round(subtotal * rng.choice([0, 0, 0.05, 0.1])) if rng.random() < 0.5 else 0
    tax = round((subtotal + service) * 0.1) if rng.random() < 0.5 else 0
    total = subtotal + service + tax
    if inconsistent:
        total += rng.choice([1000, 500, -2000])
    store = f"{rng.choice(STORE_PREFIX)} {fake.last_name()}"
    gt = {
        "doc_type": "receipt",
        "store_name": store,
        "store_address": fake.street_address() + ", " + fake.city(),
        "date": on.isoformat(),
        "time": f"{hh:02d}:{mm:02d}",
        "line_items": items,
        "subtotal": float(subtotal),
        "discount": None,
        "tax": float(tax) if tax else None,
        "service_charge": float(service) if service else None,
        "total": float(total),
        "payment_method": rng.choice(PAYMENTS),
        "document_inconsistent": inconsistent,
    }
    paid = total if gt["payment_method"] != "TUNAI" else (int(total / 50_000) + 1) * 50_000
    return SynthDoc(doc_id, "receipt", gt, {"cashier": fake.first_name(), "paid": paid, "change": paid - total,
                                            "trx": _digits(rng, 10)})


